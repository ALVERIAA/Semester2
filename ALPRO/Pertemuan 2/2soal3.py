def tampil_bilangan():
    """
    Fungsi untuk menampilkan representasi bilangan octal dan hexadecimal
    """

    # Bilangan Octal (basis 8)
    bilangan_octal = 0o745
    print("Octal 0o745 : ", bilangan_octal)

    # Bilangan Hexadecimal (basis 16) - prefix 0x
    bilangan_hexadecimal = 0xAF
    print("Hexadecimal 0xAF : ", bilangan_hexadecimal)

tampil_bilangan()